def _top_defs(tree: ast.Module) -> dict[str, list]:
    out: dict[str, list] = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            out.setdefault(node.name, []).append(node)
    return out


def _names_in(node) -> set[str]:
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}


def _def_time_names(node) -> set[str]:
    """Names a def or class statement reads when it runs, outside the body
    it defines: defaults, decorators, annotations, bases."""
    parts = list(getattr(node, "decorator_list", []))
    if isinstance(node, ast.ClassDef):
        parts += [*node.bases, *[k.value for k in node.keywords]]
    else:
        a = node.args
        parts += [*a.defaults, *[d for d in a.kw_defaults if d is not None], node.returns]
        for arg in [*a.posonlyargs, *a.args, *a.kwonlyargs, a.vararg, a.kwarg]:
            if arg is not None and arg.annotation is not None:
                parts.append(arg.annotation)
    out: set[str] = set()
    for p in parts:
        if p is not None:
            out |= _names_in(p)
    return out


def _scope_globals(table) -> set[str]:
    out = {s.get_name() for s in table.get_symbols() if s.is_global()}
    for child in table.get_children():
        out |= _scope_globals(child)
    return out


def _reads(source: str, file: str | None, nodes: dict) -> dict[str, set[str]]:
    """The module-level names each top-level def/class reads - in its body
    (Python's own symbol tables: a parameter `b` is not the global `b`)
    and when the statement runs."""
    import symtable
    top = symtable.symtable(source, file or "<model>", "exec")
    tables: dict[tuple[str, int], object] = {}
    for child in top.get_children():
        tables[(child.get_name(), child.get_lineno())] = child
    out = {}
    for k, node in nodes.items():
        table = tables.get((k, node.lineno))
        body = _scope_globals(table) if table is not None else _names_in(node)
        out[k] = body | _def_time_names(node)
    return out


class Cache:
    """The cache as one build process uses it."""

    def __init__(self, models_dir: Path, root: Path, store: Store, target: str | None = None):
        self.models_dir = Path(models_dir)
        self.root = Path(root)
        self.store = store
        self.target = target
        self.keys: dict[str, str] = {}
        self.modules: set[str] = set()          # every model/board module name in the directory
        self.handled: set[str] = set()          # the ones the finder serves
        self.stats = {"hit": [], "miss": [], "unkept": {}, "fallback": [], "step_hit": 0, "step_miss": 0}

    # -- setting up
    def scan(self) -> None:
        self.keys = module_keys(self.models_dir, self.root)
        for p in self.models_dir.glob("*.py"):
            if not p.stem.isidentifier():
                continue
            self.modules.add(p.stem)
            text = p.read_text(errors="replace")
            if GENERATED_BOARD in text or "sys.modules[__name__]" in text:
                continue                        # a board module (fast, lazy) or an alias
            if p.stem == self.target or p.stem not in self.keys:
                continue
            self.handled.add(p.stem)

    # -- import machinery
    def find_spec(self, fullname, path=None, target=None):
        if path is not None or fullname not in self.handled or fullname in sys.modules:
            return None
        file = self.models_dir / f"{fullname}.py"
        if not file.exists():
            return None
        loader = _Loader(fullname, str(file), self)
        return importlib.util.spec_from_file_location(fullname, file, loader=loader)

    def invalidate_caches(self):
        pass

    # -- the work
    def entry_key(self, name: str, flag: str | None) -> str:
        return variant(self.keys[name], flag)

    def load(self, module, name: str, vkey: str, loader) -> bool:
        got = self.store.read("m", vkey)
        if not got:
            return False
        meta, shapes = got
        t = time.monotonic()
        try:
            _fill(module, meta, shapes, loader, self)
        except Exception as exc:                        # noqa: BLE001 - a bad entry is a miss
            _debug(f"{name}: entry unreadable ({type(exc).__name__}: {exc}); running it")
            shutil.rmtree(self.store.path("m", vkey), ignore_errors=True)
            for k in [k for k in module.__dict__ if k not in _SKIP_DUNDER]:
                module.__dict__.pop(k, None)
            module.__dict__.pop("__getattr__", None)
            return False
        self.stats["hit"].append([name, round(time.monotonic() - t, 2)])
        _debug(f"{name}: from the cache in {time.monotonic() - t:.2f}s")
        return True

    def save(self, module, name: str, vkey: str, out: list, env: dict, flag: str | None) -> None:
        t = time.monotonic()
        try:
            meta, enc, unkept = _snapshot(module, name, self.modules)
        except Exception as exc:                        # noqa: BLE001 - the build goes on
            reason = str(exc) if isinstance(exc, Uncacheable) else f"{type(exc).__name__}: {exc}"
            self.stats["unkept"][name] = reason
            _debug(f"{name}: not kept ({reason})")
            return
        meta.update({"module": name, "flag": flag, "env": env, "out": out,
                     "unkept": unkept, "at": time.time()})
        try:
            self.store.write("m", vkey, meta, enc)
        except Exception as exc:                        # noqa: BLE001 - a build never fails over this
            _debug(f"{name}: could not write entry ({type(exc).__name__}: {exc})")
            return
        _debug(f"{name}: kept in {time.monotonic() - t:.2f}s"
               + (f"; run on access: {', '.join(sorted(unkept))}" if unkept else ""))


class _Loader(importlib.machinery.SourceFileLoader):
    def __init__(self, fullname, path, cache: Cache):
        super().__init__(fullname, path)
        self.cache = cache
        self.flag: str | None = None

    def exec_module(self, module):
        cache, name = self.cache, module.__name__
        flag = self.flag = os.environ.get(ENV_FLAG)
        vkey = cache.entry_key(name, flag)
        # In whatever is running now, this import is a mark, not text: its
        # output is its own entry's.
        if _CAPTURE and _CAPTURE[-1] is not None:
            _CAPTURE[-1].append(["mod", name, vkey])
        _CAPTURE.append(None)
        try:
            if cache.load(module, name, vkey, self):
                return
            with cache.store.lock("m", vkey):
                if cache.load(module, name, vkey, self):
                    return
                self._run_and_keep(module, name, vkey, flag)
        finally:
            _CAPTURE.pop()

    def _run_and_keep(self, module, name, vkey, flag):
        cache = self.cache
        env0 = dict(os.environ)
        files0 = _files(cache.root)
        out: list = []
        _CAPTURE[-1] = out
        t = time.monotonic()
        super().exec_module(module)                     # the model's own source, as always
        _CAPTURE[-1] = None
        cache.stats["miss"].append([name, round(time.monotonic() - t, 1)])
        _REPLAYED.add(name)
        if _files(cache.root) != files0:
            cache.stats["unkept"][name] = "it wrote files"
            _debug(f"{name}: not kept (it wrote files while imported)")
            return
        env1 = dict(os.environ)
        env = {k: env1.get(k) for k in set(env0) | set(env1) if env0.get(k) != env1.get(k)}
        cache.save(module, name, vkey, _merge(out), env, flag)

    def run_source(self, module):
        """The real source, in this module, after all: a name the entry could
        not keep was asked for."""
        flag = self.flag
        before = os.environ.get(ENV_FLAG)
        _set_env(ENV_FLAG, flag)
        self.cache.stats["fallback"].append(module.__name__)
        _debug(f"{module.__name__}: running its source for a name the cache does not keep")
        try:
            super().exec_module(module)
        finally:
            _set_env(ENV_FLAG, before)


def _set_env(k, v):
    if v is None:
        os.environ.pop(k, None)
    else:
        os.environ[k] = v


def _merge(out: list) -> list:
    merged: list = []
    for item in out:
        if isinstance(item, str) and merged and isinstance(merged[-1], str):
            merged[-1] += item
        else:
            merged.append(item)
    return merged


def _files(root: Path) -> dict:
    """What a module could have written: the build root without the model
    sources and the viewer's output."""
    out = {}
    for dirpath, dirnames, filenames in os.walk(root):
        if Path(dirpath) == root:
            dirnames[:] = [d for d in dirnames if d not in ("models", "assets")]
        dirnames[:] = [d for d in dirnames if d != "__pycache__"]
        for f in filenames:
            p = os.path.join(dirpath, f)
            try:
                st = os.stat(p)
                out[p] = (st.st_size, st.st_mtime_ns)
            except OSError:
                pass
    return out


def _snapshot(module, name: str, model_modules: set[str]) -> tuple[dict, Encoder, list[str]]:
    """A module that has just run, as an entry."""
    ns = module.__dict__
    if callable(ns.get("__getattr__")):
        raise Uncacheable("it has a module __getattr__ of its own")
    file = getattr(module, "__file__", None)
    source = Path(file).read_text() if file else ""
    tree = ast.parse(source)
    defs = _top_defs(tree)
    enc = Encoder(set(model_modules) - {name}, name)
    # Libraries the source imports from: `from build123d import *` binds
    # names that are best kept as "build123d's", whatever they are.
    libraries = [m for m in _imported_modules(tree)
                 if m not in model_modules and m != name and m in sys.modules]
    names: list = []          # [name, encoded] in module order
    lazy: dict = {}           # name -> ["module", m] | ["ref", m, q]: imported on first use
    redefine: dict = {}       # name -> line of its def/class
    unkept: list[str] = []
    why: dict[str, str] = {}
    for k, v in list(ns.items()):
        if k in _SKIP_DUNDER:
            continue
        dunder = k.startswith("__") and k.endswith("__")
        if dunder and k not in _KEEP_DUNDER:
            continue
        # This model's own functions and classes: defined again from source.
        if isinstance(v, (types.FunctionType, type)) and getattr(v, "__module__", None) == name \
                and getattr(v, "__qualname__", None) == k:
            node = _matching_def(defs.get(k) or [], v, file)
            # A function that has had attributes set on it is more than its def.
            if node is not None and not (isinstance(v, types.FunctionType) and v.__dict__):
                redefine[k] = node.lineno
            else:
                unkept.append(k)
                why[k] = "not made by a plain top-level def/class"
            continue
        # Another model, or something of one: imported when first used.
        if isinstance(v, types.ModuleType) and v.__name__ in model_modules and v.__name__ != name:
            lazy[k] = ["module", v.__name__]
            continue
        if isinstance(v, (types.FunctionType, type)) and getattr(v, "__module__", None) in model_modules \
                and getattr(v, "__module__", None) != name and getattr(v, "__qualname__", "") \
                and "." not in v.__qualname__ and "<" not in v.__qualname__:
            lazy[k] = ["ref", v.__module__, v.__qualname__]
            continue
        if not dunder and type(v) not in (bool, int, float, str, type(None)):
            lib = next((m for m in libraries if getattr(sys.modules[m], k, _NOTHING) is v), None)
            if lib is not None:
                names.append([k, {"ref": [lib, k]}])
                continue
        mark = enc.mark()
        try:
            names.append([k, enc.enc(v)])
        except Exception as exc:                        # noqa: BLE001 - not kept, never fatal
            enc.rollback(mark)
            if not dunder:
                unkept.append(k)
                why[k] = str(exc)[:200] or type(exc).__name__
    # A function or class is defined again from its source, reading this
    # module's names when it runs. One that reads a name that is not kept
    # would fail where the original worked: it is not kept either, until
    # nothing changes.
    reads = _reads(source, file, {k: next(n for n in defs[k] if n.lineno == line)
                                  for k, line in redefine.items()})
    defaults: dict = {}
    for k in list(redefine):
        v = ns[k]
        if isinstance(v, types.FunctionType) and (v.__defaults__ or v.__kwdefaults__):
            # Defaults as they were when the def ran, not as the names are now.
            mark = enc.mark()
            try:
                defaults[k] = [enc.enc(v.__defaults__), enc.enc(v.__kwdefaults__)]
            except Exception as exc:                    # noqa: BLE001
                enc.rollback(mark)
                redefine.pop(k)
                unkept.append(k)
                why[k] = f"defaults: {exc}"[:200]
    while True:
        bad = set(unkept)
        drop = [k for k in redefine if reads[k] & bad]
        if not drop:
            break
        for k in drop:
            redefine.pop(k)
            defaults.pop(k, None)
            unkept.append(k)
            why[k] = "reads " + ", ".join(sorted(reads[k] & bad)[:4])
    # Other models those functions read: imported with this one, not later.
    needed = set().union(*(reads[k] for k in redefine)) if redefine else set()
    eager = sorted(k for k in lazy if k in needed)
    meta = {"names": names, "objects": enc.objects, "lazy": lazy, "eager": eager, "why": why,
            "redefine": redefine, "defaults": defaults, "all": sorted(k for k in ns if not k.startswith("__")) +
            [k for k in ns if k in _KEEP_DUNDER],
            "future": [n.lineno for n in tree.body
                       if isinstance(n, ast.ImportFrom) and n.module == "__future__"]}
    return meta, enc, sorted(set(unkept))


_NOTHING = object()


def _imported_modules(tree: ast.Module) -> list[str]:
    """`from x.y import ...` and `import x.y` at the top of a source, in order."""
    out = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and not node.level and node.module:
            out.append(node.module)
        elif isinstance(node, ast.Import):
            out += [a.name for a in node.names]
    return list(dict.fromkeys(out))


def _matching_def(nodes: list, v, file) -> ast.AST | None:
    """The def/class statement that made `v` - the last one by that name
    is not always it."""
    if isinstance(v, types.FunctionType):
        code = v.__code__
        if code.co_filename != file:
            return None
        for n in nodes:
            first = min([n.lineno, *[d.lineno for d in getattr(n, "decorator_list", [])]])
            if code.co_firstlineno in (n.lineno, first) and not isinstance(n, ast.ClassDef):
                if getattr(n, "decorator_list", None):
                    return None     # a decorated function may not be what the def made
                return n
        return None
    classes = [n for n in nodes if isinstance(n, ast.ClassDef)]
    return classes[0] if len(classes) == 1 and len(nodes) == 1 else None


def _fill(module, meta: dict, shapes: Path, loader: _Loader, cache: Cache) -> None:
    """An entry into a module that is being imported."""
    ns = module.__dict__
    name = module.__name__
    # What it printed, unless that was said already in this process.
    if name not in _REPLAYED:
        _replay(meta.get("out") or [], cache)
        _REPLAYED.add(name)
    for k, v in (meta.get("env") or {}).items():
        _set_env(k, v)
    dec = Decoder(meta["objects"], shapes if shapes.exists() else None)
    for k, e in meta["names"]:
        ns[k] = dec.dec(e)
    lazy = dict(meta.get("lazy") or {})
    for k in meta.get("eager") or []:
        ns[k] = _lazy_value(lazy.pop(k))
    if meta.get("redefine"):
        source = Path(module.__file__).read_text()
        tree = ast.parse(source)
        lines = set(meta["redefine"].values()) | set(meta.get("future") or [])
        body = [n for n in tree.body if getattr(n, "lineno", None) in lines and (
            isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
            or isinstance(n, ast.ImportFrom) and n.module == "__future__")]
        code = compile(ast.Module(body=body, type_ignores=[]), module.__file__, "exec",
                       dont_inherit=True)
        exec(code, ns)                                  # noqa: S102 - the model's own defs
        for k, (pos, kw) in (meta.get("defaults") or {}).items():
            ns[k].__defaults__ = dec.dec(pos)
            ns[k].__kwdefaults__ = dec.dec(kw)
    unkept = set(meta.get("unkept") or [])
    known = set(meta.get("all") or [])

    def __getattr__(attr):
        if attr in lazy:
            value = _lazy_value(lazy.pop(attr))
            ns[attr] = value
            return value
        if attr in unkept or attr in known:
            # Not kept (or, unforeseen, kept but not restored): the source
            # runs after all, in this module, and answers.
            ns.pop("__getattr__", None)
            loader.run_source(module)
            if attr in ns:
                return ns[attr]
        raise AttributeError(f"module {name!r} has no attribute {attr!r}")

    ns["__getattr__"] = __getattr__


def _lazy_value(spec: list):
    if spec[0] == "module":
        return importlib.import_module(spec[1])
    return getattr(importlib.import_module(spec[1]), spec[2])


def _replay(out: list, cache: Cache) -> None:
    for item in out:
        if isinstance(item, str):
            sys.stdout.write(item)
            continue
        _kind, name, vkey = item
        if name in sys.modules or name in _REPLAYED:
            continue
        got = cache.store.read("m", vkey)
        if got:
            _REPLAYED.add(name)
            _replay(got[0].get("out") or [], cache)


