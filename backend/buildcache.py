class Uncacheable(Exception):
    """A value the cache cannot keep faithfully."""


_FUNC = (types.FunctionType, types.BuiltinFunctionType, type)
_SKIP_DUNDER = {"__name__", "__file__", "__loader__", "__spec__", "__package__", "__builtins__",
                "__cached__", "__path__", "__getattr__", "__dir__"}
_KEEP_DUNDER = {"__doc__", "__all__", "__annotations__"}


def _resolve(module: str, qualname: str):
    obj = importlib.import_module(module)
    for part in qualname.split("."):
        obj = getattr(obj, part)
    return obj


class Encoder:
    """Values to JSON plus a list of OCCT shapes (written with BinTools).

    Scalars are themselves; anything else is a tagged dict. Lists, dicts,
    sets and build123d objects go into an object table and are referred to
    as {"o": i}, so a shape held by two names is one shape after loading,
    and the parent/children links of a Compound survive."""

    def __init__(self, model_modules: set[str], self_name: str = ""):
        self.model_modules = model_modules
        self.self_name = self_name
        self.objects: list = []
        self.memo: dict[int, int] = {}
        self.keep: list = []                 # alive, so no id() is reused meanwhile
        self.shapes: list = []
        self.shape_memo: dict[int, int] = {}
        self.vertex = None
        self.uses_models: set[str] = set()   # model modules the values refer to

    # -- helpers
    def _table(self, obj, make):
        i = self.memo.get(id(obj))
        if i is not None:
            return {"o": i}
        i = len(self.objects)
        self.objects.append(None)
        self.memo[id(obj)] = i
        self.keep.append(obj)
        self.objects[i] = make()
        return {"o": i}

    def mark(self) -> tuple[int, int]:
        return len(self.objects), len(self.shapes)

    def rollback(self, mark: tuple[int, int]) -> None:
        """Forget what a value that failed half way put in the tables."""
        n, m = mark
        del self.objects[n:]
        del self.shapes[m:]
        self.memo = {k: i for k, i in self.memo.items() if i < n}
        self.shape_memo = {k: i for k, i in self.shape_memo.items() if i < m}

    def _topo(self, s) -> int:
        i = self.shape_memo.get(id(s))
        if i is None:
            i = len(self.shapes)
            self.shapes.append(s)
            self.shape_memo[id(s)] = i
            self.keep.append(s)
        return i

    def _loc_index(self, loc) -> int:
        """A TopLoc_Location kept exactly: on a vertex, in the shape file."""
        if self.vertex is None:
            from OCP.BRepBuilderAPI import BRepBuilderAPI_MakeVertex
            from OCP.gp import gp_Pnt
            self.vertex = BRepBuilderAPI_MakeVertex(gp_Pnt(0, 0, 0)).Vertex()
        i = len(self.shapes)
        self.shapes.append(self.vertex.Located(loc))
        return i

    def class_ref(self, cls, models: bool = False) -> list[str]:
        """A class by where it is defined. `models`: another model's class
        will do (a NamedTuple: its instances are only their items)."""
        mod, qual = getattr(cls, "__module__", None), getattr(cls, "__qualname__", None)
        if not mod or not qual or "<" in qual:
            raise Uncacheable(f"{cls!r} has no importable name")
        if mod == self.self_name or (mod in self.model_modules and not models):
            raise Uncacheable(f"{qual} is defined by a model ({mod})")
        if mod in self.model_modules:
            self.uses_models.add(mod)
        try:
            if _resolve(mod, qual) is not cls:
                raise Uncacheable(f"{mod}.{qual} is not that class")
        except Uncacheable:
            raise
        except Exception as exc:                        # noqa: BLE001
            raise Uncacheable(f"{mod}.{qual}: {exc}") from exc
        return [mod, qual]

    def ref(self, obj) -> dict:
        """A function, class or other named thing, by where it is defined."""
        mod, qual = getattr(obj, "__module__", None), getattr(obj, "__qualname__", None)
        if not mod or not qual or "<" in qual:
            raise Uncacheable(f"{obj!r} has no importable name")
        if mod == self.self_name:
            raise Uncacheable(f"{qual} is defined here")
        if mod in self.model_modules:
            # Another model's function: that model resolves it on loading.
            if "." in qual:
                raise Uncacheable(f"{mod}.{qual} is not top-level")
            self.uses_models.add(mod)
            return {"ref": [mod, qual]}
        try:
            if _resolve(mod, qual) is not obj:
                raise Uncacheable(f"{mod}.{qual} is not the same object")
        except Uncacheable:
            raise
        except Exception as exc:                        # noqa: BLE001
            raise Uncacheable(f"{mod}.{qual}: {exc}") from exc
        return {"ref": [mod, qual]}

    # -- the walk
    def enc(self, v):
        t = type(v)
        if v is None or t in (bool, int, str, float):
            return v
        if t is tuple:
            return {"tuple": [self.enc(x) for x in v]}
        if t is list:
            return self._table(v, lambda: {"list": [self.enc(x) for x in v]})
        if t is dict:
            return self._table(v, lambda: {"dict": [[self.enc(k), self.enc(x)] for k, x in v.items()]})
        if t is set:
            return self._table(v, lambda: {"set": [self.enc(x) for x in v]})
        if t is frozenset:
            return {"frozenset": [self.enc(x) for x in v]}
        if t is bytes:
            return {"bytes": base64.b64encode(v).decode()}
        if t is complex:
            return {"complex": [v.real, v.imag]}
        if isinstance(v, types.ModuleType):
            if v.__name__ in self.model_modules:
                self.uses_models.add(v.__name__)
            if sys.modules.get(v.__name__) is not v:
                raise Uncacheable(f"module {v.__name__} is not the imported one")
            return {"module": v.__name__}
        if isinstance(v, enum.Enum):
            return {"enum": [self.class_ref(t), v.name]}
        if isinstance(v, pathlib.PurePath):
            return {"path": [self.class_ref(t), str(v)]}
        if isinstance(v, _FUNC):
            return self.ref(v)
        ocp = self._ocp(v, t)
        if ocp is not None:
            return ocp
        if isinstance(v, tuple):                        # a NamedTuple, a board's Hole...
            return {"ntuple": [self.class_ref(t, models=True), [self.enc(x) for x in v]]}
        mod = getattr(t, "__module__", "") or ""
        if mod == "build123d" or mod.startswith("build123d."):
            return self._b123d(v, t)
        raise Uncacheable(f"{t.__module__}.{t.__qualname__} is not kept")

    def _ocp(self, v, t):
        mod = getattr(t, "__module__", "") or ""
        if not mod.startswith("OCP"):
            return None
        from OCP.TopoDS import TopoDS_Shape
        if isinstance(v, TopoDS_Shape):
            return None if v.IsNull() else {"topo": self._topo(v)}
        name = t.__name__
        if name == "TopLoc_Location":
            return {"loc": self._loc_index(v)}
        if name == "gp_Trsf":
            from OCP.TopLoc import TopLoc_Location
            return {"trsf": self._loc_index(TopLoc_Location(v))}
        if name in ("gp_Vec", "gp_Pnt", "gp_Dir", "gp_XYZ"):
            return {name: [v.X(), v.Y(), v.Z()]}
        if name == "gp_Ax1":
            return {name: [self.enc(v.Location()), self.enc(v.Direction())]}
        if name in ("gp_Ax2", "gp_Ax3"):
            out = [self.enc(v.Location()), self.enc(v.Direction()), self.enc(v.XDirection())]
            if name == "gp_Ax3":
                out.append(bool(v.Direct()))
            return {name: out}
        if name == "gp_Pln":
            return {name: self.enc(v.Position())}
        if name in ("Quantity_ColorRGBA", "Quantity_Color"):
            from OCP.Quantity import Quantity_TOC_RGB
            rgb = v.GetRGB() if name == "Quantity_ColorRGBA" else v
            vals = list(rgb.Values(Quantity_TOC_RGB))
            if name == "Quantity_ColorRGBA":
                vals.append(v.Alpha())
            return {name: vals}
        if name == "gp_GTrsf":
            return {name: [v.Value(r, c) for r in (1, 2, 3) for c in (1, 2, 3, 4)]}
        if name == "Bnd_Box":
            if v.IsVoid():
                return {name: None}
            if v.IsOpen() or v.IsWhole():
                raise Uncacheable("an open Bnd_Box")
            # The corners come with the gap added; the box is kept as it is
            # stored (corners, gap) when that gives the same corners back.
            g = v.GetGap()
            lo, hi = v.CornerMin().Coord(), v.CornerMax().Coord()
            raw = [x + g for x in lo] + [x - g for x in hi]
            if g and all(r - g == x for r, x in zip(raw[:3], lo)) \
                    and all(r + g == x for r, x in zip(raw[3:], hi)):
                return {name: [*raw, g]}
            return {name: [*lo, *hi, 0.0]}
        if isinstance(v, enum.Enum) or hasattr(t, "__members__"):
            return {"enum": [self.class_ref(t), v.name]}
        raise Uncacheable(f"OCP {name} is not kept")

    def _b123d(self, v, t):
        from build123d.build_common import Builder
        from build123d.topology.shape_core import Shape
        cls = self.class_ref(t)
        is_shape, is_builder = isinstance(v, Shape), isinstance(v, Builder)

        def attrs():
            out = []
            for k, x in (getattr(v, "__dict__", None) or {}).items():
                if is_shape and k == "_history":
                    x = None              # how it was made, not what it is
                elif is_builder and (isinstance(x, (types.FrameType, types.GeneratorType))
                                     or type(x).__name__ == "_GeneratorContextManager"):
                    x = None              # a closed builder's link to the code that ran it
                out.append([k, self.enc(x)])
            return out

        if isinstance(v, list):
            return self._table(v, lambda: {"lsub": cls, "items": [self.enc(x) for x in v], "d": attrs()})
        if isinstance(v, dict):
            raise Uncacheable(f"{t.__qualname__}: a dict subclass")
        if isinstance(v, tuple):
            return {"ntuple": [cls, [self.enc(x) for x in v]]}
        if not hasattr(v, "__dict__"):
            raise Uncacheable(f"{t.__qualname__} has no __dict__")
        return self._table(v, lambda: {"obj": cls, "d": attrs()})

    def write_shapes(self, path: Path) -> None:
        from OCP.BinTools import BinTools
        from OCP.BRep import BRep_Builder
        from OCP.TopoDS import TopoDS_Compound
        comp = TopoDS_Compound()
        b = BRep_Builder()
        b.MakeCompound(comp)
        for s in self.shapes:
            b.Add(comp, s)
        # A write that failed half way (disk full, memory) is not an entry:
        # Store.write would rename it into place for every later build to
        # parse.
        if not BinTools.Write_s(comp, str(path)) or not Path(path).stat().st_size:
            raise OSError(f"BinTools could not write {path}")


class Decoder:
    def __init__(self, objects: list, shapes_path: Path | None):
        self.objects = objects
        self.done: dict[int, object] = {}
        self.shapes: list = []
        if shapes_path is not None and shapes_path.exists():
            from OCP.BinTools import BinTools
            from OCP.TopoDS import TopoDS_Iterator, TopoDS_Shape
            from build123d.topology.shape_core import downcast
            whole = TopoDS_Shape()
            # Read whole or not at all: a file pruned or cut short under us
            # is an unreadable entry (a miss), never a half-read shape.
            if not BinTools.Read_s(whole, str(shapes_path)) or whole.IsNull():
                raise ValueError(f"{shapes_path}: not a whole BinTools file")
            it = TopoDS_Iterator(whole)
            while it.More():
                self.shapes.append(downcast(it.Value()))
                it.Next()

    def dec(self, e):
        if e is None or type(e) in (bool, int, str, float):
            return e
        if "o" in e:
            return self.obj(e["o"])
        tag, val = next(iter(e.items()))
        if tag == "tuple":
            return tuple(self.dec(x) for x in val)
        if tag == "frozenset":
            return frozenset(self.dec(x) for x in val)
        if tag == "bytes":
            return base64.b64decode(val)
        if tag == "complex":
            return complex(*val)
        if tag == "module":
            return importlib.import_module(val)
        if tag == "ref":
            return _resolve(*val)
        if tag == "enum":
            return getattr(_resolve(*val[0]), val[1])
        if tag == "path":
            return _resolve(*val[0])(val[1])
        if tag == "ntuple":
            cls = _resolve(*val[0])
            items = [self.dec(x) for x in val[1]]
            return cls._make(items) if hasattr(cls, "_make") else tuple.__new__(cls, items)
        if tag == "topo":
            return self.shapes[val]
        if tag == "loc":
            return self.shapes[val].Location()
        if tag == "trsf":
            return self.shapes[val].Location().Transformation()
        from OCP import gp
        if tag in ("gp_Vec", "gp_Pnt", "gp_Dir", "gp_XYZ"):
            return getattr(gp, tag)(*val)
        if tag == "gp_Ax1":
            return gp.gp_Ax1(self.dec(val[0]), self.dec(val[1]))
        if tag == "gp_Ax2":
            return gp.gp_Ax2(self.dec(val[0]), self.dec(val[1]), self.dec(val[2]))
        if tag == "gp_Ax3":
            ax = gp.gp_Ax3(self.dec(val[0]), self.dec(val[1]), self.dec(val[2]))
            if not val[3]:
                ax.YReverse()
            return ax
        if tag == "gp_Pln":
            return gp.gp_Pln(self.dec(val))
        if tag in ("Quantity_ColorRGBA", "Quantity_Color"):
            from OCP.Quantity import Quantity_Color, Quantity_ColorRGBA, Quantity_TOC_RGB
            c = Quantity_Color(val[0], val[1], val[2], Quantity_TOC_RGB)
            return Quantity_ColorRGBA(c, val[3]) if tag == "Quantity_ColorRGBA" else c
        if tag == "Bnd_Box":
            from OCP.Bnd import Bnd_Box
            box = Bnd_Box()
            if val is not None:
                box.Update(*val[:6])
                if val[6]:
                    box.SetGap(val[6])
            return box
        if tag == "gp_GTrsf":
            g = gp.gp_GTrsf()
            for i, x in enumerate(val):
                g.SetValue(i // 4 + 1, i % 4 + 1, x)
            return g
        raise ValueError(f"unknown tag {tag}")

    def obj(self, i: int):
        if i in self.done:
            return self.done[i]
        e = self.objects[i]
        tag, val = next(iter(e.items()))
        if tag == "list":
            out = []
            self.done[i] = out
            out.extend(self.dec(x) for x in val)
        elif tag == "dict":
            out = {}
            self.done[i] = out
            for k, x in val:
                out[self.dec(k)] = self.dec(x)
        elif tag == "set":
            out = set()
            self.done[i] = out
            out.update(self.dec(x) for x in val)
        elif tag == "lsub":
            cls = _resolve(*val)
            out = cls.__new__(cls)
            self.done[i] = out
            list.extend(out, [self.dec(x) for x in e["items"]])
            for k, x in e["d"]:
                out.__dict__[k] = self.dec(x)
        elif tag == "obj":
            cls = _resolve(*val)
            out = cls.__new__(cls)
            self.done[i] = out
            for k, x in e["d"]:
                out.__dict__[k] = self.dec(x)
        else:
            raise ValueError(f"unknown object {tag}")
        return out


def encode_value(value, model_modules: set[str] = frozenset()) -> tuple[dict, Encoder]:
    """One value (an imported STEP, say) as an entry's meta and shapes."""
    enc = Encoder(set(model_modules))
    data = enc.enc(value)
    return {"value": data, "objects": enc.objects}, enc


# ---------------------------------------------------------------- the store

class Store:
    def __init__(self, root: Path):
        self.root = Path(root)

    def path(self, kind: str, key: str) -> Path:
        return self.root / kind / key[:2] / key

    def has(self, kind: str, key: str) -> bool:
        return (self.path(kind, key) / "meta.json").exists()

    def read(self, kind: str, key: str) -> tuple[dict, Path] | None:
        p = self.path(kind, key)
        try:
            meta = json.loads((p / "meta.json").read_text())
        except (OSError, ValueError):
            return None
        if meta.get("format") != FORMAT:
            return None
        try:
            os.utime(p / "meta.json")                   # recently used: pruned last
        except OSError:
            pass
        return meta, p / "shapes.bin"

    def write(self, kind: str, key: str, meta: dict, enc: Encoder) -> None:
        final = self.path(kind, key)
        if (final / "meta.json").exists():
            return
        final.parent.mkdir(parents=True, exist_ok=True)
        tmp = final.parent / f".{key}.{os.getpid()}.tmp"
        shutil.rmtree(tmp, ignore_errors=True)
        tmp.mkdir()
        try:
            if enc.shapes:
                enc.write_shapes(tmp / "shapes.bin")
            (tmp / "meta.json").write_text(json.dumps({"format": FORMAT, **meta}))
            try:
                os.rename(tmp, final)
            except OSError:                             # another process was first
                shutil.rmtree(tmp, ignore_errors=True)
        except BaseException:
            shutil.rmtree(tmp, ignore_errors=True)
            raise

    def lock(self, kind: str, key: str) -> "_Lock":
        return _Lock(self.root / "locks" / f"{kind}-{key}.lock")

    def prune(self, limit: int) -> int:
        """Least recently used entries out until the cache fits in `limit`
        bytes. Returns how many went."""
        entries = []
        total = 0
        for kind in ("m", "step"):
            for meta in (self.root / kind).glob("*/*/meta.json"):
                d = meta.parent
                try:
                    size = sum(f.stat().st_size for f in d.iterdir())
                    entries.append((meta.stat().st_mtime, size, d))
                except OSError:
                    continue
                total += size
        gone = 0
        for _at, size, d in sorted(entries):
            if total <= limit:
                break
            shutil.rmtree(d, ignore_errors=True)
            total -= size
            gone += 1
        return gone


class _Lock:
    """An exclusive lock between build processes: the second waits for the
    first to finish computing an entry instead of computing it too."""

    def __init__(self, path: Path):
        self.path = path
        self.fd = None

    def __enter__(self):
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.fd = os.open(self.path, os.O_RDWR | os.O_CREAT, 0o644)
        except OSError:
            self.fd = None
            return self
        deadline = time.monotonic() + LOCK_WAIT
        while True:
            try:
                fcntl.flock(self.fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                return self
            except BlockingIOError:
                if time.monotonic() > deadline:     # go ahead without it
                    os.close(self.fd)
                    self.fd = None
                    return self
                time.sleep(0.2)

    def __exit__(self, *exc):
        if self.fd is not None:
            try:
                fcntl.flock(self.fd, fcntl.LOCK_UN)
            finally:
                os.close(self.fd)
                self.fd = None


def _size(text: str) -> int:
    text = (text or "").strip().upper()
    mult = {"K": 2**10, "M": 2**20, "G": 2**30, "T": 2**40}
    try:
        if text and text[-1] in mult:
            return int(float(text[:-1]) * mult[text[-1]])
        return int(text)
    except ValueError:
        return 4 * 2**30


