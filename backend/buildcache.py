"""Component result cache: a model another one imports is its saved result,
not a fresh run of its source - Fusion's idea of a referenced component.

A build runs `export_model.py` in a fresh process, and every model it
imports used to be executed from its source again: the lid, the button
caps, the light pipes, the base and the station each spent two minutes
re-running the enclosure before doing a few seconds of their own work.

What is kept (`<cache>/m/<key>/`), right after a model module has run as
someone's import:

    meta.json   its module-level names: plain data (numbers, strings,
                lists, dicts, tuples...) and build123d objects (shapes,
                locations, planes, vectors, colours) with their labels,
                colours and Compound children, encoded as a small object
                table; names bound to modules or to things importable from
                elsewhere (`from build123d import Box`) as references;
                which top-level `def`s and `class`es to define again; what
                it printed and what it set in os.environ.
    shapes.bin  every OCCT shape those names hold, one BinTools file (so
                sub-shapes shared between names stay shared, triangulation
                included).

The key is content-addressed: the module's own text, its name, the keys of
every model it imports (transitively; for a bare `import lid`, the model
the importer's project resolves it to - backend/modnames.py), the uploaded files and board STEPs
its text names, REDLINE_IMPORT_ONLY at the moment it is imported, and the
versions of Python, build123d, OCP, this file and backend/assembly.py
(whose component marks the kept shapes carry). A pinned component is
written into the build directory at its pinned source, so its key - and its
cache entry - is the pinned version's. Nothing has to be invalidated: a
change anywhere below gives a different key.

Using it: `install()` puts a finder in front of the import system for the
build directory's model modules. Importing one whose entry exists fills the
module from the entry, defines its top-level functions and classes again
from the real source (same file, same line numbers, globals = the module),
and hangs a module `__getattr__` on it: a name that could not be kept (a
lambda, an open file, an instance of a class the model defines...) runs the
real source on first access, in that module, so the answer is the same,
only later. A missing entry runs the real source as before and keeps the
result. While one process computes an entry, another waiting for the same
key blocks on a lock instead of computing it a second time.

Board STEPs: `build123d.import_step` is wrapped for the build, so a large
STEP (a board's `B.part`, an uploaded bracket) is parsed once per file
content and read back as BREP afterwards.

    REDLINE_BUILD_CACHE        the directory (default <repo>/.cache/build),
                               or "off" to build without it
    REDLINE_BUILD_CACHE_MAX    size to prune to, e.g. 4G (default)
    REDLINE_BUILD_CACHE_DEBUG  1: say what the cache did on stderr

Stdlib only at import time: the subprocess imports this before build123d.
"""

