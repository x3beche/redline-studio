def install(models_dir: Path, root: Path | None = None, target: str | None = None) -> Cache | None:
    """Serve the build directory's models from the cache (export_model.py,
    before the model is loaded). None when the cache is off."""
    where = directory()
    if where is None:
        return None
    models_dir = Path(models_dir)
    root = Path(root) if root else models_dir.parent
    store = Store(where)
    cache = Cache(models_dir, root, store, target)
    try:
        cache.scan()
    except Exception as exc:                            # noqa: BLE001 - build as before
        _debug(f"not used: {type(exc).__name__}: {exc}")
        return None
    if not isinstance(sys.stdout, _Tee):
        sys.stdout = _Tee(sys.stdout)
    if not isinstance(sys.stderr, _Tee):
        sys.stderr = _Tee(sys.stderr)
    sys.meta_path.insert(0, cache)
    cache.wrap_steps = lambda: wrap_import_step(store, cache.stats)
    try:
        cache.wrap_steps()
    except Exception as exc:                            # noqa: BLE001
        _debug(f"STEP cache not used: {exc}")
    return cache


def finish(cache: Cache | None, report: Path | None = None) -> None:
    """After the build: what the cache did - into `report` (JSON, next to
    the viewer payload, for the build to pass on) and, with DEBUG, stderr -
    and the cache kept within its size."""
    if cache is None:
        return
    _debug(json.dumps(cache.stats))
    if report is not None:
        try:
            Path(report).write_text(json.dumps(cache.stats))
        except OSError:
            pass
    try:
        cache.store.prune(_size(os.environ.get("REDLINE_BUILD_CACHE_MAX", "4G")))
    except Exception:                                   # noqa: BLE001
        pass
