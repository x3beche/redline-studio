def imported_names(source: str) -> list[str]:
    """The top-level modules a source imports - the same reading as
    backend/links.py `imported_names` (kept here so the build subprocess
    does not import the backend)."""
    try:
        tree = ast.parse(source or "")
    except SyntaxError:
        return []
    out = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            out += [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module:
            out.append(node.module.split(".")[0])
        elif (isinstance(node, ast.Call) and node.args
              and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)
              and ((isinstance(node.func, ast.Attribute) and node.func.attr == "import_module")
                   or (isinstance(node.func, ast.Name) and node.func.id == "__import__"))):
            out.append(node.args[0].value.split(".")[0])
    return list(dict.fromkeys(out))


_RUNTIME: str | None = None


def runtime() -> str:
    """What else a result depends on: this file and backend/assembly.py
    (the component marks on its shapes), Python, build123d, OCP."""
    global _RUNTIME
    if _RUNTIME is None:
        import importlib.metadata as md
        import platform
        # The interpreter's version, not sys.version: that also names the
        # compiler and the day it was built, which differ between the
        # API container and the host's .venv - so a build an agent ran
        # never used what a link rebuild had kept, and the other way
        # round, with the same Python, build123d and OCP on both.
        python = f"{platform.python_implementation()} {platform.python_version()}"
        parts = [str(FORMAT), python, _sha(Path(__file__).read_bytes())[:16]]
        # The marks a kept shape carries are made there (component grouping).
        marks = Path(__file__).with_name("assembly.py")
        if marks.exists():
            parts.append(_sha(marks.read_bytes())[:16])
        for dist in ("build123d", "cadquery-ocp", "cadquery_ocp", "cadquery-ocp-novtk",
                     "ocp-viewer-core", "numpy", "scipy"):
            try:
                parts.append(f"{dist}={md.version(dist)}")
            except Exception:                           # noqa: BLE001 - not installed under that name
                pass
        # Which files make up the geometry libraries, by their hashes: the
        # same version installed twice is the same library, a patched one is
        # not.
        for dist in ("build123d", "cadquery-ocp-novtk"):
            try:
                parts.append(f"{dist} files={_installed_files(md.distribution(dist))}")
            except Exception:                           # noqa: BLE001 - not installed under that name
                pass
        try:
            import OCP
            parts.append(f"OCP={getattr(OCP, '__version__', '?')}")
        except Exception:                               # noqa: BLE001
            pass
        _RUNTIME = _sha("|".join(parts))
    return _RUNTIME


def _installed_files(dist) -> str:
    """A digest of a distribution's own files as its RECORD lists them,
    without what the installer adds (pip and uv write different ones)."""
    rows = []
    for line in (dist.read_text("RECORD") or "").splitlines():
        path = line.split(",", 1)[0]
        if not line or "__pycache__" in path or ".dist-info/" in path:
            continue
        rows.append(line)
    return _sha("\n".join(sorted(rows)))[:16]


def module_keys(models_dir: Path, root: Path, resolve=None) -> dict[str, str]:
    """Every importable module in the build directory and its key: its text,
    its name, the files its text names, and the keys of the modules it
    imports - the modules those imports load for this importer (a bare
    `import lid` is iot-fan's lid in iot-fan and the 80 mm one's there:
    `resolve(importer, name)`, backend/modnames.py; by default the
    manifest of the directory). A module in an import cycle has none."""
    models_dir, root = Path(models_dir), Path(root)
    if resolve is None:
        from . import modnames
        resolve = modnames.resolver(models_dir)
    texts = {p.stem: p.read_text(errors="replace") for p in sorted(models_dir.glob("*.py"))
             if p.stem.isidentifier()}
    # Files a model can open by name: uploads in the build root, board STEPs.
    files = [p for p in root.iterdir() if p.is_file()] if root.is_dir() else []
    boards = root / "_boards"
    if boards.is_dir():
        files += [p for p in boards.iterdir() if p.is_file()]
    file_sha: dict[Path, str] = {}

    keys: dict[str, str | None] = {}
    visiting: set[str] = set()

    def key(name: str) -> str | None:
        if name in keys:
            return keys[name]
        if name in visiting:
            return None
        visiting.add(name)
        text = texts[name]
        deps = []
        ok = True
        try:
            loads = {resolve(name, n) for n in imported_names(text)}
        except ImportError:                 # several models by that name: the build stops
            loads, ok = set(), False
        for dep in sorted(n for n in loads if n in texts and n != name):
            k = key(dep)
            if k is None:
                ok = False
            deps.append((dep, k))
        named = []
        for p in files:
            if p.name in text:
                if p not in file_sha:
                    file_sha[p] = _file_sha(p)
                named.append((p.name, file_sha[p]))
        visiting.discard(name)
        keys[name] = _sha(json.dumps([runtime(), name, _sha(text), deps, sorted(named)])) if ok else None
        return keys[name]

    for n in texts:
        key(n)
    return {n: k for n, k in keys.items() if k}


def variant(key: str, flag: str | None) -> str:
    """The entry for a module imported with REDLINE_IMPORT_ONLY = `flag`:
    a part behaves differently on its own (STANDALONE) and imported."""
    return _sha(f"{key}|{ENV_FLAG}={flag!r}")


