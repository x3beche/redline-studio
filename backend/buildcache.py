def wrap_import_step(store: Store, stats: dict | None = None) -> None:
    """build123d.import_step reads a large file once per content: after
    that, the same Compound - children, labels and colours - from BREP."""
    import build123d
    import build123d.importers as importers
    original = getattr(importers.import_step, "__redline_original__", importers.import_step)
    stats = stats if stats is not None else {}

    def import_step(filename, *args, **kwargs):
        try:
            path = Path(os.fsdecode(filename))
            big = path.stat().st_size >= STEP_MIN
        except (OSError, TypeError):
            big = False
        if not big:
            return original(filename, *args, **kwargs)
        key = _sha(json.dumps([runtime(), "import_step", _file_sha(path), repr(args),
                               repr(sorted(kwargs.items()))]))
        for attempt in (1, 2):
            got = store.read("step", key)
            if got:
                try:
                    meta, shapes = got
                    value = Decoder(meta["objects"], shapes).dec(meta["value"])
                    stats["step_hit"] = stats.get("step_hit", 0) + 1
                    _debug(f"STEP {path.name}: from the cache")
                    return value
                except Exception as exc:                # noqa: BLE001
                    _debug(f"STEP {path.name}: entry unreadable ({exc})")
                    shutil.rmtree(store.path("step", key), ignore_errors=True)
            if attempt == 2:
                break
            with store.lock("step", key):
                if store.has("step", key):
                    continue
                value = original(filename, *args, **kwargs)
                stats["step_miss"] = stats.get("step_miss", 0) + 1
                try:
                    meta, enc = encode_value(value)
                    store.write("step", key, meta, enc)
                except Exception as exc:                # noqa: BLE001 - kept or not, it is read
                    _debug(f"STEP {path.name}: not kept ({type(exc).__name__}: {exc})")
                return value
        return original(filename, *args, **kwargs)

    import_step.__redline_original__ = original
    import_step.__wrapped__ = original
    import_step.__doc__ = original.__doc__
    importers.import_step = import_step
    build123d.import_step = import_step


