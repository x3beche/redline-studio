def directory() -> Path | None:
    """Where entries live, or None when the cache is off."""
    raw = os.environ.get("REDLINE_BUILD_CACHE", "").strip()
    if raw.lower() in ("off", "0", "no", "false"):
        return None
    return Path(raw) if raw else REPO / ".cache" / "build"


def default_parallel() -> int:
    """Link rebuilds at once when REDLINE_LINK_BUILDS does not say: one per
    ~10 GB of memory (the build ceiling, tools/capped.sh) and per four
    hardware threads, at most three. 32 GB and 16 threads: 3."""
    try:
        mem = os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES") / 2**30
    except (ValueError, OSError, AttributeError):
        mem = 16
    cpus = os.cpu_count() or 4
    return max(1, min(3, int(mem // 10), cpus // 4))


def _debug(msg: str) -> None:
    if os.environ.get("REDLINE_BUILD_CACHE_DEBUG") == "1":
        print(f"[build cache] {msg}", file=sys.__stderr__, flush=True)


def _sha(data: bytes | str) -> str:
    if isinstance(data, str):
        data = data.encode()
    return hashlib.sha256(data).hexdigest()


def _file_sha(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


